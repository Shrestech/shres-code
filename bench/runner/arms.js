/**
 * Arm registry: the measured interventions. An arm is a name plus the exact
 * jspace plugin config it applies; everything else in the harness composition
 * stays identical so the toggle is the only difference between arms.
 *
 * The shipped `shres-base` bundle already mounts the `jspace` row with
 * `enabled: false`, so both arms are expressed as an explicit `--patch`
 * overlay that replaces that row's complete config (patch rows replace, never
 * deep-merge). Pinning the off arm too keeps `run.json`'s `armConfig` honest
 * when shipped defaults drift.
 *
 * @module bench/runner/arms
 */

/**
 * Registered arms, in run order. `off` is the baseline every comparison is
 * against and always runs first in the interleave.
 */
export const ARMS = Object.freeze({
  off: Object.freeze({
    name: 'off',
    jspace: Object.freeze({ enabled: false, mode: 'available', requireCoverage: true }),
  }),
  on: Object.freeze({
    name: 'on',
    jspace: Object.freeze({ enabled: true, mode: 'available', requireCoverage: true }),
  }),
})

/**
 * List registered arm names in run order.
 * @returns {string[]} arm names; `off` first.
 */
export function listArms() {
  return Object.keys(ARMS)
}

/**
 * Look up one arm by name. Unknown names fail loud with the valid set.
 * @param {string} name - arm name from `--arms`.
 * @returns {{ name: string, jspace: Record<string, unknown> }} the arm entry.
 */
export function getArm(name) {
  const arm = ARMS[name]
  if (!arm) throw new Error(`unknown arm "${name}" (registered: ${listArms().join(', ')})`)
  return arm
}

/**
 * Render the `--patch` overlay for one trial. Besides the jspace toggle, the
 * overlay redirects session persistence into a per-trial root with
 * `compression: none` so the runner can locate and line-read the log without
 * the zstd codec, and re-pins the `agent-default-model` row so the measured
 * provider/model cannot drift with shipped defaults or user settings (patch
 * rows replace, never deep-merge, and that row's config is exactly
 * `{ provider, model }`). Strings are JSON-quoted, which is valid YAML.
 *
 * With `contextWindow`, the overlay additionally replaces the `llm-pi-ai`
 * row's providers map with just ollama-cloud, its model entries pinned to the
 * given token capacity — patch replacement is wholesale, so the reduced map is
 * only safe because bench trials resolve exactly one pinned provider. The pin
 * is harness-side: compaction-basic derives its threshold from the model's
 * contextWindow, while the provider keeps serving its true (larger) window, so
 * a small pin forces genuine mid-task compaction without truncating requests.
 * @param {{ name: string, jspace: Record<string, unknown> }} arm - arm entry from {@link getArm}.
 * @param {{ sessionLogRoot: string, provider: string, model: string, contextWindow?: number }} options - absolute per-trial persistence root, the pinned route, and an optional harness-side context-window pin.
 * @returns {string} the overlay YAML document.
 */
export function renderArmOverlay(arm, { sessionLogRoot, provider, model, contextWindow }) {
  const jspaceRows = Object.entries(arm.jspace)
    .map(([key, value]) => `    ${key}: ${JSON.stringify(value)}`)
    .join('\n')
  const windowRow = contextWindow === undefined ? '' : renderContextWindowRow(provider, contextWindow)
  return `# Generated by bench/runner for arm "${arm.name}". Applied as \`shres --patch\`.
- id: jspace
  config:
${jspaceRows}
- id: agent-default-model
  config:
    provider: ${JSON.stringify(provider)}
    model: ${JSON.stringify(model)}
- id: session-persistence-jsonl
  config:
    root: ${JSON.stringify(sessionLogRoot)}
    compression: none
${windowRow}`
}

/**
 * Render the llm-pi-ai provider row pinning both ollama-cloud model entries to
 * one context-window capacity. Values mirror the shipped
 * `packages/bundle/base/cordis.patch.yml` row; `runner.test.js` pins them
 * against that file so drift fails loud.
 * @param {string} provider - the pinned provider; only `ollama-cloud` is reproducible here.
 * @param {number} contextWindow - token capacity to pin on every ollama-cloud model.
 * @returns {string} the overlay YAML row, newline-terminated.
 */
function renderContextWindowRow(provider, contextWindow) {
  if (provider !== 'ollama-cloud') {
    throw new Error(`--context-window cannot be pinned for provider "${provider}" (only ollama-cloud is reproducible in the overlay)`)
  }
  return `- id: llm-pi-ai
  config:
    providers:
      ollama-cloud:
        displayName: Ollama Cloud
        api: openai-completions
        baseURL: https://ollama.com/v1
        apiKeyEnv: OLLAMA_API_KEY
        models:
          - id: deepseek-v4-flash:cloud
            name: DeepSeek V4 Flash (cloud)
            contextWindow: ${contextWindow}
            maxTokens: 32768
          - id: deepseek-v4-pro:cloud
            name: DeepSeek V4 Pro (cloud)
            contextWindow: ${contextWindow}
            maxTokens: 32768
`
}
